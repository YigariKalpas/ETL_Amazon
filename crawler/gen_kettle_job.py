# -*- coding: utf-8 -*-
"""生成 PDI/Kettle 作业框架（j_etl_pipeline.kjb + 每步 .cmd 包装 + 冒烟作业）。

结构参考 PDI 9.4 自带样例（samples/jobs/...）：
  - 成功/失败用 DUMMY 特殊项，不用 success/fail 子元素；
  - SHELL 项字段为 filename / exec_per_row / set_logfile / logfile / loglevel 等；
  - Shell 项不适合传静态参数，因此每步生成一个 ASCII .cmd 包装，Kettle 只负责调用与分支。

用法：
  python crawler/gen_kettle_job.py
  scripts\\pdi.cmd kitchen /file:E:\\ETL_Amazon\\etl\\jobs\\j_smoke.kjb
"""
from __future__ import annotations

import io
import os
import sys

ROOT = r"E:\\ETL_Amazon"
JOBS = os.path.join(ROOT, "etl", "jobs")
STEPDIR = os.path.join(JOBS, "steps")
OUT = os.path.join(JOBS, "j_etl_pipeline.kjb")
SMOKE = os.path.join(JOBS, "j_smoke.kjb")

STEPS = [
    ("01_parse_pages", "parse_product_page.py", "", "parse snapshots to staging json"),
    ("02_classify", "classify_products.py", ' --rules "%PROJECT_ROOT%\\design\\classify_rules_v0.4.json"', "task3 classification"),
    ("03_movie_entities", "movie_entities.py", "", "task4 entity resolution"),
    ("04_person_entities", "person_entities.py", "", "task5 person resolution"),
    ("05_field_assertions", "build_field_assertions.py", "", "task9 lineage assertions"),
    ("06_build_target", "build_target_db.py", "", "load sqlite target"),
    ("07_release_dates", "release_dates.py", "", "task6 release dates"),
    ("08_field_conflicts", "field_conflicts.py", "", "task7 field selection"),
    ("09_dedup_reviews", "dedup_reviews.py", "", "task8 review dedup"),
    ("10_build_target2", "build_target_db.py", "", "reload sqlite target"),
    ("11_load_pg", "load_target_pg.py", "", "sync postgres"),
    ("12_verify_target", "verify_target_db.py", "", "verify target db"),
]


def write_cmd(name: str, script: str, extra_args: str) -> None:
    body = (
        "@echo off\r\n"
        "rem generated by crawler/gen_kettle_job.py - keep ASCII only\r\n"
        "setlocal\r\n"
        'set "PROJECT_ROOT=%~dp0..\\..\\.."\r\n'
        'for %%I in ("%PROJECT_ROOT%") do set "PROJECT_ROOT=%%~fI"\r\n'
        '"%PROJECT_ROOT%\\.venv\\Scripts\\python.exe" -u "%PROJECT_ROOT%\\crawler\\@@SCRIPT@@"@@ARGS@@\r\n'
        "exit /b %ERRORLEVEL%\r\n"
    ).replace("@@SCRIPT@@", script).replace("@@ARGS@@", extra_args)
    path = os.path.join(STEPDIR, name + ".cmd")
    with io.open(path, "w", encoding="ascii", newline="") as fh:
        fh.write(body)


def special(name: str, x: int, y: int, start: str, dummy: str) -> str:
    return ("    <entry>\n"
            "      <name>%s</name>\n"
            "      <description/>\n"
            "      <type>SPECIAL</type>\n"
            "      <start>%s</start>\n"
            "      <dummy>%s</dummy>\n"
            "      <repeat>N</repeat>\n"
            "      <schedulerType>0</schedulerType>\n"
            "      <intervalSeconds>0</intervalSeconds>\n"
            "      <intervalMinutes>0</intervalMinutes>\n"
            "      <hour>12</hour>\n"
            "      <minutes>0</minutes>\n"
            "      <weekDay>1</weekDay>\n"
            "      <DayOfMonth>1</DayOfMonth>\n"
            "      <parallel>N</parallel>\n"
            "      <draw>Y</draw>\n"
            "      <nr>0</nr>\n"
            "      <xloc>%d</xloc>\n"
            "      <yloc>%d</yloc>\n"
            "    </entry>\n" % (name, start, dummy, x, y))


def shell(name: str, x: int, y: int) -> str:
    return ("    <entry>\n"
            "      <name>%s</name>\n"
            "      <description/>\n"
            "      <type>SHELL</type>\n"
            "      <filename>${PROJECT_ROOT}/etl/jobs/steps/%s.cmd</filename>\n"
            "      <arg_from_previous>N</arg_from_previous>\n"
            "      <exec_per_row>N</exec_per_row>\n"
            "      <set_logfile>Y</set_logfile>\n"
            "      <logfile>${PROJECT_ROOT}/logs/pdi_%s.log</logfile>\n"
            "      <logext/>\n"
            "      <add_date>N</add_date>\n"
            "      <add_time>N</add_time>\n"
            "      <loglevel>Basic</loglevel>\n"
            "      <parallel>N</parallel>\n"
            "      <draw>Y</draw>\n"
            "      <nr>0</nr>\n"
            "      <xloc>%d</xloc>\n"
            "      <yloc>%d</yloc>\n"
            "    </entry>\n" % (name, name, name, x, y))


def hop(src: str, dst: str, evaluation: str, unconditional: str) -> str:
    return ("    <hop>\n"
            "      <from>%s</from>\n"
            "      <to>%s</to>\n"
            "      <from_nr>0</from_nr>\n"
            "      <to_nr>0</to_nr>\n"
            "      <enabled>Y</enabled>\n"
            "      <evaluation>%s</evaluation>\n"
            "      <unconditional>%s</unconditional>\n"
            "    </hop>\n" % (src, dst, evaluation, unconditional))


HEAD = """<?xml version="1.0" encoding="UTF-8"?>
<job>
  <name>%s</name>
  <description>%s</description>
  <extended_description/>
  <job_version/>
  <job_status>0</job_status>
  <directory>/</directory>
  <parameters>
    <parameter><name>PROJECT_ROOT</name><default_value>E:/ETL_Amazon</default_value><description>project root</description></parameter>
  </parameters>
  <entries>
"""

TAIL = """  </entries>
  <hops>
%s  </hops>
  <notepads>
  </notepads>
  <info>
    <name>%s</name>
    <description/>
    <extended_description/>
    <job_version/>
    <directory>/</directory>
    <created_user>-</created_user>
    <created_date>2026/10/28</created_date>
    <modified_user>-</modified_user>
    <modified_date>2026/10/28</modified_date>
  </info>
</job>
"""


def emit(path: str, job_name: str, desc: str, steps) -> None:
    parts = [HEAD % (job_name, desc)]
    parts.append(special("Start", 100, 100, "Y", "N"))
    parts.append(special("Success", 1200, 60, "N", "Y"))
    parts.append(special("Failure", 1200, 300, "N", "Y"))
    for i, (name, _s, _a, _d) in enumerate(steps, start=1):
        parts.append(shell(name, 300 + ((i - 1) % 3) * 220, 120 + ((i - 1) // 3) * 140))
    hops = []
    prev = "Start"
    for name, _s, _a, _d in steps:
        hops.append(hop(prev, name, "Y", "N" if prev != "Start" else "Y"))
        hops.append(hop(prev, "Failure", "N", "N"))
        prev = name
    hops.append(hop(prev, "Success", "Y", "N"))
    parts.append(TAIL % ("".join(hops), job_name))
    with io.open(path, "w", encoding="utf-8") as fh:
        fh.write("".join(parts))
    print("wrote %-18s steps=%d" % (os.path.basename(path), len(steps)))


def main() -> int:
    os.makedirs(STEPDIR, exist_ok=True)
    # 【KEY-83】.cmd 必须纯 ASCII：把中文名规则文件复制一份 ASCII 名的副本
    src_rules = os.path.join(ROOT, "design", "产品分类规则_v0.4.json")
    dst_rules = os.path.join(ROOT, "design", "classify_rules_v0.4.json")
    if os.path.isfile(src_rules):
        import shutil
        shutil.copyfile(src_rules, dst_rules)
        print("rules copy -> design/classify_rules_v0.4.json")
    for name, script, args, _d in STEPS:
        write_cmd(name, script, args)
    write_cmd("00_verify", "verify_target_db.py", "")
    emit(OUT, "j_etl_pipeline",
         "Amazon ETL: parse -> classify -> entities -> persons -> lineage -> dedup -> target -> PG", STEPS)
    emit(SMOKE, "j_smoke", "PDI smoke: single fast step (verify target db)",
         [("00_verify", "verify_target_db.py", "", "verify target db")])
    return 0


if __name__ == "__main__":
    sys.exit(main())